String myanmarSoundex(String input) {
  final buffer = StringBuffer();
  for (final unit in input.runes) {
    final code = String.fromCharCode(unit);
    final mapped = myanmarConsonantMap[code];
    if (mapped != null && mapped.isNotEmpty) {
      buffer.write(mapped);
    } else if (unit >= 0x0041 && unit <= 0x005A) {
      buffer.write(String.fromCharCode(unit + 32));
    } else if (unit >= 0x0061 && unit <= 0x007A) {
      buffer.write(code);
    }
  }
  return buffer.toString();
}